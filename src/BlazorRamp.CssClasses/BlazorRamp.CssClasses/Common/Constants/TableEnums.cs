using BlazorRamp.CssClasses.Common.Utilities;

namespace BlazorRamp.CssClasses.Common.Constants;

/// <summary>
/// Sets a 1-based column position, used to target a whole table column (header and body
/// cells together) for alignment via <see cref="Table.AlignColumn"/>.
/// </summary>
