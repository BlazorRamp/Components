{
    /// <summary>The 1st column.</summary>
    One = 1,

    /// <summary>
    /// The 2nd column.
    /// </summary>
    Two = 2,

    /// <summary>
    /// The 3rd column.
    /// </summary>
    Three = 3,

    /// <summary>
    /// The 4th column.
    /// </summary>
    Four = 4,

    /// <summary>
    /// The 5th column.
    /// </summary>
    Five = 5,

    /// <summary>
    /// The 6th column.
    /// </summary>
    Six = 6,

    /// <summary>
    /// The 7th column.
    /// </summary>
    Seven = 7,

    /// <summary>
    /// The 8th column.
    /// </summary>
    Eight = 8,

    /// <summary>
    /// The 9th column.
    /// </summary>
    Nine = 9,

    /// <summary>
    /// The 10th column.
    /// </summary>
    Ten = 10,

    /// <summary>
    /// The 11th column.
    /// </summary>
    Eleven = 11,

    /// <summary>
    /// The 12th column.
    /// </summary>
    Twelve = 12
}